from __future__ import annotations

import json
import re


def _task_id(value: str) -> str:
    normalized = re.sub(r"[^a-zA-Z0-9_]+", "_", str(value)).strip("_").lower()
    return normalized or "task"


def render_dag_source(manifest: dict) -> str:
    dag_id = re.sub(r"[^a-zA-Z0-9_]+", "_", str(manifest.get("dag_id") or "metavault_load"))[:180]
    schedule = manifest.get("schedule")
    schedule_literal = "None" if schedule in (None, "manual") else repr(str(schedule))
    task_ids = [_task_id(task) for task in manifest.get("tasks", [])]
    if not task_ids:
        task_ids = ["load_plan"]
    safe_manifest = {key: value for key, value in manifest.items() if key.lower() not in {"password", "token", "api_key", "secret", "connection_string"}}
    manifest_literal = repr(json.dumps(safe_manifest, ensure_ascii=False, sort_keys=True))
    task_declarations = "\n".join(f"    {task} = EmptyOperator(task_id={task!r})" for task in task_ids)
    chain = " >> ".join(task_ids)
    return f'''"""Generated by MetaVault. Do not edit manually; redeploy from the load plan."""\nimport json\nfrom datetime import datetime\nfrom airflow import DAG
from airflow.operators.empty import EmptyOperator

DAG_MANIFEST = json.loads({manifest_literal})

with DAG(
    dag_id={dag_id!r},
    schedule={schedule_literal},
    start_date=datetime(2024, 1, 1),
    catchup=False,
    max_active_runs=1,
    tags=["metavault", "datalake", {str(manifest.get("load_mode", "INIT"))!r}],
) as dag:
{task_declarations}
    {chain}
'''
